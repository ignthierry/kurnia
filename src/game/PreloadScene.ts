export class PreloadScene extends Phaser.Scene {
  constructor() {
    super('PreloadScene');
  }

  preload(): void {
    // aset pixel art dari folder /game
    this.load.image('fairy', 'game/atlas/char-stand.png');
    this.load.image('fairyWalk', 'game/atlas/char-walk.png');
    this.load.image('forestBg', 'game/atlas/forest-bg.png');
    this.load.image('coins', 'game/atlas/coins.png');
    this.load.image('crystals', 'game/atlas/crystals.png');
  }

  create(): void {
    createGameTextures(this);

    // animasi peri dari strip walk (grid frameWidth manual)
    if (!this.anims.exists('fairy-walk')) {
      this.textures.addSpriteSheet('fairyWalkGrid', textureSource(this, 'fairyWalk'), {
        frameWidth: 135,
        frameHeight: 160,
      });
      this.anims.create({
        key: 'fairy-walk',
        frames: this.anims.generateFrameNumbers('fairyWalkGrid', {
          start: 0,
          end: 6,
        }),
        frameRate: 10,
        repeat: -1,
      });
    }

    // level data (spawn player, portal, musuh) per level
    const levelConfigs = [
      {
        playerSpawn: { x: 60, y: 540 },
        portal: { x: 560, y: 420 },
        orbs: [
          { x: 150, y: 460 },
          { x: 300, y: 380 },
          { x: 450, y: 320 },
        ],
        bats: [
          { x: 240, y: 320 },
          { x: 420, y: 260 },
        ],
        thornPlants: [
          { x: 350, y: 540 },
        ],
      },
    ];

    this.registry.set('levelConfigs', levelConfigs);
    this.scene.start('GameScene');
  }
}