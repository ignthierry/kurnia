// helper: ambil source image dari texture (buat addSpriteSheet)
function textureSource(scene: Phaser.Scene, key: string): HTMLImageElement {
  const tex = scene.textures.get(key);
  const src = tex.getSourceImage();
  if (!(src instanceof HTMLImageElement)) {
    throw new Error(`texture ${key} bukan HTMLImageElement`);
  }
  return src;
}

